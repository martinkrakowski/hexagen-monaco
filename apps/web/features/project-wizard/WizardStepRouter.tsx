import {
  WorkspaceGovernanceStep,
  BoundedContextStep,
  PeerContextMappingStep,
  PortConfigurationStep,
  SummaryStep,
} from "./steps";
import { wizardSteps } from "./config";
import type { ViewMode } from "@/types/view-mode";
import type { ManifestCompleteness } from "./utils/analyzeManifestCompleteness";

/**
 * Props for the WizardStepRouter component.
 */
interface WizardStepRouterProps {
  /** The 0-based index of the current step in the wizard */
  currentStepIndex: number;
  /** Total number of steps available in the wizard */
  totalSteps: number;
  /** Whether the user has fulfilled all requirements to proceed to the next step */
  canProceed: boolean;
  /** Whether a project generation is currently in progress */
  isGenerating: boolean;
  /** ID of the bounded context currently selected for editing */
  activeContextId: string;
  /** ID of the peer mapping currently selected for editing */
  activeMappingId: string;
  /** Information indicating which steps were pre-filled via an imported or AI-generated manifest */
  autoGeneratedSteps: ManifestCompleteness | null;
  /** Callback fired when a bounded context is selected */
  onContextSelect: (id: string) => void;
  /** Callback fired when a peer mapping is selected */
  onMappingSelect: (id: string) => void;
  /** Callback to progress to the next wizard step */
  onNext: () => void;
  /** Callback to return to the previous wizard step */
  onBack: () => void;
  /** Callback to open the saved projects dialog */
  onShowSavedProjects: () => void;
  /** Callback to finalize and generate the project */
  onGenerate: () => void;
  /** Callback to change the overarching view mode */
  onViewModeChange: (mode: ViewMode) => void;
}

/**
 * Routes and renders the correct wizard step component based on the current step index.
 * Passes necessary state and callbacks down to the specific step views.
 *
 * @param props - Component properties
 */
export function WizardStepRouter({
  currentStepIndex,
  totalSteps,
  canProceed,
  isGenerating,
  activeContextId,
  activeMappingId,
  autoGeneratedSteps,
  onContextSelect,
  onMappingSelect,
  onNext,
  onBack,
  onShowSavedProjects,
  onGenerate,
  onViewModeChange,
}: WizardStepRouterProps) {
  const currentStepConfig = wizardSteps[currentStepIndex];
  const title = currentStepConfig?.title ?? "";
  const description = currentStepConfig?.description ?? "";

  switch (currentStepIndex) {
    case 0:
      return (
        <WorkspaceGovernanceStep
          onNext={onNext}
          onShowSavedProjects={onShowSavedProjects}
          canProceed={canProceed}
          currentStep={1}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={autoGeneratedSteps?.governance}
        />
      );
    case 1:
      return (
        <BoundedContextStep
          onNext={onNext}
          onBack={onBack}
          canProceed={canProceed}
          activeContextId={activeContextId}
          onContextSelect={onContextSelect}
          currentStep={2}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={autoGeneratedSteps?.boundedContexts}
        />
      );
    case 2:
      return (
        <PeerContextMappingStep
          onNext={onNext}
          onBack={onBack}
          canProceed={canProceed}
          activeMappingId={activeMappingId}
          onMappingSelect={onMappingSelect}
          currentStep={3}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={autoGeneratedSteps?.peerMappings}
        />
      );
    case 3:
      return (
        <PortConfigurationStep
          onNext={onNext}
          onBack={onBack}
          canProceed={canProceed}
          currentStep={4}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={autoGeneratedSteps?.portConfiguration}
        />
      );
    case 4:
      return (
        <SummaryStep
          onBack={onBack}
          onGenerate={onGenerate}
          canProceed={canProceed}
          isGenerating={isGenerating}
          onViewModeChange={onViewModeChange}
          currentStep={5}
          totalSteps={totalSteps}
          title={title}
          description={description}
        />
      );
    default:
      return null;
  }
}
