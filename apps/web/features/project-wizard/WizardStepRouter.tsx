import {
  WorkspaceGovernanceStep,
  ApplicationsStep,
  BoundedContextStep,
  PeerContextMappingStep,
  PortConfigurationStep,
  AddOnsStep,
  TemplateQuestionsStep,
  SummaryStep,
} from "./steps";
import { wizardSteps } from "./config";
import type { ViewMode } from "@/types/view-mode";

import { useWizardLifecycleContext } from "../workspace-shell/contexts/WizardLifecycleContext";

/**
 * Props for the WizardStepRouter component.
 */
interface WizardStepRouterProps {
  currentStepIndex: number;
  totalSteps: number;
  onViewModeChange: (mode: ViewMode) => void;
  activeContextId: string;
  activeMappingId: string;
  onContextSelect: (id: string) => void;
  onMappingSelect: (id: string) => void;
}

/**
 * Routes and renders the correct wizard step component based on the current step index.
 * Consumes lifecycle values from WizardLifecycleContext.
 */
export function WizardStepRouter({
  currentStepIndex,
  totalSteps,
  onViewModeChange,
  activeContextId,
  activeMappingId,
  onContextSelect,
  onMappingSelect,
}: WizardStepRouterProps) {
  const lifecycle = useWizardLifecycleContext();
  const currentStepConfig = wizardSteps[currentStepIndex];
  const title = currentStepConfig?.title ?? "";
  const description = currentStepConfig?.description ?? "";
  // 1-based label for the footer ("Step N of M"), derived from the index so
  // inserting/reordering a step needs no manual renumbering.
  const stepNumber = currentStepIndex + 1;

  // Dispatch by stable step `id` (not numeric index) so the ADR-0041 Applications
  // insertion — and any future step change — can't silently misroute.
  switch (currentStepConfig?.id) {
    case "workspace_governance":
      return (
        <WorkspaceGovernanceStep
          onNext={lifecycle.handleNext}
          canProceed={lifecycle.canProceed(currentStepIndex)}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={lifecycle.autoGeneratedSteps?.governance}
        />
      );
    case "applications":
      return (
        <ApplicationsStep
          onNext={lifecycle.handleNext}
          onBack={lifecycle.handleBack}
          canProceed={lifecycle.canProceed(currentStepIndex)}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={lifecycle.autoGeneratedSteps?.boundedContexts}
        />
      );
    case "bounded_contexts":
      return (
        <BoundedContextStep
          onNext={lifecycle.handleNext}
          onBack={lifecycle.handleBack}
          canProceed={lifecycle.canProceed(currentStepIndex)}
          activeContextId={activeContextId}
          onContextSelect={onContextSelect}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={lifecycle.autoGeneratedSteps?.boundedContexts}
        />
      );
    case "peer_mappings":
      return (
        <PeerContextMappingStep
          onNext={lifecycle.handleNext}
          onBack={lifecycle.handleBack}
          canProceed={lifecycle.canProceed(currentStepIndex)}
          activeMappingId={activeMappingId}
          onMappingSelect={onMappingSelect}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={lifecycle.autoGeneratedSteps?.peerMappings}
        />
      );
    case "ports_configuration":
      return (
        <PortConfigurationStep
          onNext={lifecycle.handleNext}
          onBack={lifecycle.handleBack}
          canProceed={lifecycle.canProceed(currentStepIndex)}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
          readOnly={lifecycle.autoGeneratedSteps?.portConfiguration}
          // Saved manifest for the imported-project read-only ports banner
          // (import round-trip integrity, Item 1.4). Null outside edit mode;
          // the step only reads it when manifestSource === "imported".
          importedManifestYaml={lifecycle.loadedProject?.manifestYaml ?? null}
        />
      );
    case "add_ons":
      return (
        <AddOnsStep
          onNext={lifecycle.handleNext}
          onBack={lifecycle.handleBack}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
        />
      );
    case "template_questions":
      return (
        <TemplateQuestionsStep
          onNext={lifecycle.handleNext}
          onBack={lifecycle.handleBack}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
        />
      );
    case "summary":
      return (
        <SummaryStep
          onBack={lifecycle.handleBack}
          onGenerate={lifecycle.handleGenerate}
          canProceed={lifecycle.canProceed(currentStepIndex)}
          isGenerating={lifecycle.isGenerating}
          onViewModeChange={onViewModeChange}
          currentStep={stepNumber}
          totalSteps={totalSteps}
          title={title}
          description={description}
        />
      );
    default:
      return null;
  }
}
