import { describe, it } from "node:test";
import assert from "node:assert";
import { promises as fs } from "node:fs";
import path from "node:path";
import yaml from "js-yaml";
import { generateArchitectureFiles } from "../../src/generators/architecture-files.js";
import type { Manifest } from "../../src/types/manifest.js";
import { makeCapturingLogger } from "../helpers/spy-logger.js";
import {
  withTempWorkspace,
  pathExists,
  readText,
} from "../helpers/fs-helpers.js";
import { makeConfig } from "../helpers/test-config.js";

const GENERATED_MARKER = "// @generated by @hexagen/sync";

describe("architecture files", () => {
  it("should create all architecture files in external mode on fresh target", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const manifest: Manifest = {
        system: "demo",
        scope: "demo",
        architecture: "modular-monolith",
        bounded_contexts: [{ name: "shared" }],
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
      });

      const result = await generateArchitectureFiles(config);

      const manifestPath = path.join(archDir, "manifest.yaml");
      const layerRulesPath = path.join(
        archDir,
        "invariants",
        "layer-rules.yaml",
      );
      const linterPath = path.join(archDir, "invariants", "linter-config.yaml");
      const genConfigPath = path.join(archDir, "generator.config.yaml");

      assert.strictEqual(
        await pathExists(manifestPath),
        true,
        "external fresh target should materialise .architecture/manifest.yaml",
      );
      assert.strictEqual(
        await pathExists(layerRulesPath),
        true,
        "external fresh target should materialise invariants/layer-rules.yaml",
      );
      assert.strictEqual(
        await pathExists(linterPath),
        true,
        "external fresh target should materialise invariants/linter-config.yaml",
      );
      assert.strictEqual(
        await pathExists(genConfigPath),
        true,
        "external fresh target should materialise generator.config.yaml",
      );

      const createdSet = new Set(result.created);
      assert.ok(
        createdSet.has(manifestPath),
        "result.created should include the manifest path",
      );
      assert.ok(
        createdSet.has(layerRulesPath) &&
          createdSet.has(linterPath) &&
          createdSet.has(genConfigPath),
        "result.created should include all three invariant/config files",
      );
      assert.strictEqual(
        result.totalOps,
        4,
        "totalOps should equal 4 when all four files are freshly created",
      );
    });
  });

  it("should create manifest.yaml via yaml.dump when absent in external mode", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const manifest: Manifest = {
        system: "yaml-dump-target",
        scope: "yd",
        architecture: "modular-monolith",
        bounded_contexts: [{ name: "alpha" }],
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
      });

      await generateArchitectureFiles(config);

      const manifestPath = path.join(archDir, "manifest.yaml");
      const raw = await readText(manifestPath);
      const parsed = yaml.load(raw) as Manifest;

      assert.strictEqual(
        parsed.system,
        "yaml-dump-target",
        "dumped manifest must round-trip the `system` field",
      );
      assert.strictEqual(
        parsed.scope,
        "yd",
        "dumped manifest must round-trip the `scope` field",
      );
      assert.deepStrictEqual(
        parsed.bounded_contexts,
        [{ name: "alpha" }],
        "dumped manifest must round-trip the bounded_contexts array",
      );
    });
  });

  it("should preserve existing manifest.yaml in external mode", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      await fs.mkdir(archDir, { recursive: true });
      const manifestPath = path.join(archDir, "manifest.yaml");
      const sentinel =
        "# user-edited manifest — must be preserved verbatim\nsystem: user-owned\n";
      await fs.writeFile(manifestPath, sentinel, "utf8");

      const manifest: Manifest = {
        system: "engine-supplied",
        bounded_contexts: [{ name: "beta" }],
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
      });

      const result = await generateArchitectureFiles(config);

      const afterContent = await readText(manifestPath);
      assert.strictEqual(
        afterContent,
        sentinel,
        "external mode must NEVER overwrite an existing manifest.yaml (ALWAYS protected)",
      );
      assert.ok(
        result.skipped.includes(manifestPath),
        "manifest.yaml should appear in result.skipped when preserved",
      );
      assert.ok(
        !result.created.includes(manifestPath),
        "manifest.yaml must not appear in result.created when it already exists",
      );
    });
  });

  it("should skip manifest.yaml entirely in self-regen mode", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const manifest: Manifest = {
        system: "self-regen-demo",
        bounded_contexts: [{ name: "gamma" }],
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "self-regen",
        forceRoot: true,
      });

      const result = await generateArchitectureFiles(config);

      const manifestPath = path.join(archDir, "manifest.yaml");
      assert.strictEqual(
        await pathExists(manifestPath),
        false,
        "self-regen mode must never create .architecture/manifest.yaml",
      );
      assert.ok(
        !result.created.includes(manifestPath) &&
          !result.skipped.includes(manifestPath) &&
          !result.updated.includes(manifestPath),
        "self-regen mode must not record manifest.yaml in any result bucket (early return)",
      );
    });
  });

  it("should regenerate stale @generated invariant file in self-regen with forceRoot", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const invariantsDir = path.join(archDir, "invariants");
      await fs.mkdir(invariantsDir, { recursive: true });
      const layerRulesPath = path.join(invariantsDir, "layer-rules.yaml");
      const stale = `${GENERATED_MARKER}\n# stale generated content — should be replaced\n`;
      await fs.writeFile(layerRulesPath, stale, "utf8");

      const manifest: Manifest = {
        scope: "regen",
        architecture: "modular-monolith",
        bounded_contexts: [{ name: "shared" }],
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "self-regen",
        forceRoot: true,
      });

      const result = await generateArchitectureFiles(config);

      const after = await readText(layerRulesPath);
      assert.notStrictEqual(
        after,
        stale,
        "self-regen with forceRoot should overwrite stale @generated invariant file",
      );
      assert.ok(
        after.includes("@regen/shared"),
        "regenerated layer-rules.yaml should contain interpolated scope `@regen/shared`",
      );
      assert.ok(
        result.updated.includes(layerRulesPath),
        "layer-rules.yaml should appear in result.updated when regenerated",
      );
    });
  });

  it("should preserve user-customised invariant file in self-regen without forceRoot", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const invariantsDir = path.join(archDir, "invariants");
      await fs.mkdir(invariantsDir, { recursive: true });
      const layerRulesPath = path.join(invariantsDir, "layer-rules.yaml");
      const custom =
        "# user customisation — no @generated marker\nlayers:\n  domain:\n    custom: true\n";
      await fs.writeFile(layerRulesPath, custom, "utf8");

      const manifest: Manifest = {
        scope: "regen2",
        bounded_contexts: [{ name: "shared" }],
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "self-regen",
        forceRoot: false,
      });

      const result = await generateArchitectureFiles(config);

      const after = await readText(layerRulesPath);
      assert.strictEqual(
        after,
        custom,
        "self-regen without forceRoot must preserve user-customised invariant file",
      );
      assert.ok(
        result.skipped.includes(layerRulesPath),
        "preserved file should be recorded under result.skipped (protected root)",
      );
      assert.ok(
        !result.updated.includes(layerRulesPath),
        "preserved file must not appear in result.updated",
      );
    });
  });

  it("should use manifest monorepo archInvariants templates when present", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const manifest: Manifest = {
        scope: "demo",
        architecture: "modular-monolith",
        bounded_contexts: [{ name: "shared" }],
        monorepo: {
          archInvariants: {
            layerRules: {
              template:
                "# CUSTOM layer-rules for {scope} ({workspaceTemplate})\ncustom: true\n",
            },
            linterConfig: {
              template: "# CUSTOM linter-config for @{scope}/shared\n",
            },
            generatorConfig: {
              template:
                "# CUSTOM generator-config — workspace={workspaceTemplate}\n",
            },
          },
        },
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
      });

      await generateArchitectureFiles(config);

      const layerRules = await readText(
        path.join(archDir, "invariants", "layer-rules.yaml"),
      );
      const linter = await readText(
        path.join(archDir, "invariants", "linter-config.yaml"),
      );
      const genCfg = await readText(
        path.join(archDir, "generator.config.yaml"),
      );

      assert.ok(
        layerRules.startsWith(
          "# CUSTOM layer-rules for demo (modular-monolith)",
        ),
        "manifest-supplied layerRules template should be used and interpolated",
      );
      assert.ok(
        linter.includes("# CUSTOM linter-config for @demo/shared"),
        "manifest-supplied linterConfig template should be used and interpolated",
      );
      assert.ok(
        genCfg.includes(
          "# CUSTOM generator-config — workspace=modular-monolith",
        ),
        "manifest-supplied generatorConfig template should be used and interpolated",
      );
    });
  });

  it("should use built-in templates and interpolate scope when archInvariants absent", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const manifest: Manifest = {
        scope: "acme",
        workspaceTemplate: "strict-enterprise",
        bounded_contexts: [{ name: "shared" }],
      } as Manifest;
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
      });

      await generateArchitectureFiles(config);

      const layerRules = await readText(
        path.join(archDir, "invariants", "layer-rules.yaml"),
      );
      const linter = await readText(
        path.join(archDir, "invariants", "linter-config.yaml"),
      );

      assert.ok(
        layerRules.includes(
          "Template: strict-enterprise — event-bus boundaries",
        ),
        "built-in strict-enterprise layer-rules should be emitted when archInvariants absent",
      );
      assert.ok(
        layerRules.includes('required_communication: "event-bus"'),
        "built-in strict-enterprise layer-rules should include event-bus cross-context rule",
      );
      assert.ok(
        linter.includes("(strict mode)") &&
          linter.includes("deny_sibling_imports: true"),
        "built-in strict-enterprise linter-config should emit the strict rule set",
      );
      assert.ok(
        linter.includes('"@acme/shared"'),
        "linter-config should interpolate the manifest scope into @{scope}/shared",
      );
    });
  });

  it("should interpolate {scope}, {template}, {workspaceTemplate}, and {ownershipBlock}", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const manifest: Manifest = {
        scope: "octo",
        architecture: "microservices",
        bounded_contexts: [
          {
            name: "catalog",
            layers: {
              application: {
                ports: {
                  in: ["search.in-port.ts"],
                  out: ["repository.out-port.ts"],
                },
              },
              infrastructure: {
                adapters: ["postgres.adapter.ts"],
              },
            },
          },
        ],
        monorepo: {
          archInvariants: {
            layerRules: {
              template:
                "scope={scope}\ntemplate={template}\nworkspaceTemplate={workspaceTemplate}\n",
            },
            generatorConfig: {
              template: "ports:\n{ownershipBlock}\n",
            },
          },
        },
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
      });

      await generateArchitectureFiles(config);

      const layerRules = await readText(
        path.join(archDir, "invariants", "layer-rules.yaml"),
      );
      assert.ok(
        layerRules.includes("scope=octo"),
        "{scope} must be interpolated to the manifest scope",
      );
      assert.ok(
        layerRules.includes("template=microservices"),
        "{template} must be interpolated to the workspace-template alias",
      );
      assert.ok(
        layerRules.includes("workspaceTemplate=microservices"),
        "{workspaceTemplate} must be interpolated to the same value as {template}",
      );

      const genCfg = await readText(
        path.join(archDir, "generator.config.yaml"),
      );
      assert.ok(
        genCfg.includes("      Search: catalog") &&
          genCfg.includes("      Repository: catalog") &&
          genCfg.includes("      Postgres: catalog"),
        "{ownershipBlock} must expand to PascalCase'd ports/adapters mapped to bounded context",
      );
    });
  });

  it("should build ownership block with correct context assignments", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const archDir = path.join(workspaceRoot, ".architecture");
      const manifest: Manifest = {
        scope: "own",
        architecture: "modular-monolith",
        bounded_contexts: [
          { name: "shared" },
          {
            name: "orders",
            layers: {
              application: {
                ports: {
                  in: ["place-order.in-port.ts", "cancel.in-port.ts"],
                  out: ["order-repository.out-port.ts"],
                },
              },
              infrastructure: {
                adapters: ["sql-order-repository.adapter.ts"],
              },
            },
          },
          {
            name: "billing",
            layers: {},
          },
        ],
      };
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
      });

      await generateArchitectureFiles(config);

      const genCfg = await readText(
        path.join(archDir, "generator.config.yaml"),
      );

      for (const expected of [
        "      PlaceOrder: orders",
        "      Cancel: orders",
        "      OrderRepository: orders",
        "      SqlOrderRepository: orders",
      ]) {
        assert.ok(
          genCfg.includes(expected),
          `ownership block should include "${expected}"`,
        );
      }

      const idx = genCfg.indexOf("ownership-registry:");
      assert.ok(
        idx !== -1,
        "generator.config.yaml must include ownership-registry",
      );
      const ownershipSection = genCfg.slice(idx);
      assert.ok(
        !/:\s*shared$/m.test(ownershipSection),
        "no port/adapter should be owned by `shared` — the context is skipped",
      );
      assert.ok(
        !/:\s*billing$/m.test(ownershipSection),
        "context without ports/adapters should not contribute ownership entries",
      );
    });
  });

  it("should warn on unresolved template placeholders", async () => {
    await withTempWorkspace(async ({ workspaceRoot }) => {
      const manifest: Manifest = {
        scope: "warn",
        bounded_contexts: [{ name: "shared" }],
        monorepo: {
          archInvariants: {
            layerRules: {
              template: "unresolved: {doesNotExist}\n",
            },
          },
        },
      };
      const capture = makeCapturingLogger();
      const config = makeConfig(workspaceRoot, manifest, {
        mode: "external",
        forceRoot: true,
        logger: capture.logger,
      });

      await generateArchitectureFiles(config);

      const hasWarning = capture.logs.some(
        (w) =>
          w.level === "warn" &&
          w.message.includes("architecture-files: unresolved placeholder") &&
          w.message.includes("doesNotExist") &&
          w.message.includes("invariants/layer-rules.yaml"),
      );
      assert.ok(
        hasWarning,
        "missing placeholder should surface as a logger.warn with label + variable name",
      );
    });
  });
});
