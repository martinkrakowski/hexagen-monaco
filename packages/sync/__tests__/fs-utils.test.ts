describe("safeWriteFileAtomic", () => {
  let workspaceRoot: string;

  beforeEach(async () => {
    workspaceRoot = await makeTmpWorkspace();
  });

  afterEach(async () => {
    await fs.rm(workspaceRoot, { recursive: true, force: true });
  });

  describe("dry-run", () => {
    it("does not mutate disk when file exists with different content", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "x.ts");
      const original = `${GENERATED_MARKER}\nexport const v = 1;\n`;
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, original, "utf8");

      const config = makeConfig(workspaceRoot, { dryRun: true });
      const status = await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const v = 2;\n`,
        config,
      );

      assert.equal(status, "updated", "dry-run reports prospective 'updated'");
      assert.equal(
        await fs.readFile(target, "utf8"),
        original,
        "dry-run MUST NOT modify existing content",
      );
    });

    it("does not create the file when it is absent", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "new.ts");
      const config = makeConfig(workspaceRoot, { dryRun: true });

      const status = await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const v = 1;\n`,
        config,
      );

      assert.equal(status, "created", "dry-run reports prospective 'created'");
      assert.equal(
        await pathExists(target),
        false,
        "dry-run MUST NOT create a file on disk",
      );
    });

    it("reports a protected root file as 'protected', not 'updated' (honest preview)", async () => {
      // A real run skips protected roots without --force-root, so the dry-run
      // preview must report the same outcome — otherwise the change set is
      // inflated with files that would never actually be written.
      const target = path.join(workspaceRoot, "turbo.json");
      await fs.writeFile(target, `{"old":true}\n`, "utf8");

      const config = makeConfig(workspaceRoot, { dryRun: true });
      const status = await safeWriteFileAtomic(
        target,
        `{"new":true}\n`,
        config,
      );

      assert.equal(
        status,
        "protected",
        "dry-run must report a protected root as 'protected', not 'updated'",
      );
      assert.equal(
        await fs.readFile(target, "utf8"),
        `{"old":true}\n`,
        "dry-run MUST NOT modify a protected root",
      );
    });

    it("reports an existing hand-written (unmarked) file as 'skipped', not 'updated'", async () => {
      // No @generated marker → a real run preserves it (returns 'skipped').
      // The preview must match, not claim it 'would update'.
      const target = path.join(
        workspaceRoot,
        "packages",
        "a",
        "src",
        "hand.ts",
      );
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, "export const handWritten = true;\n", "utf8");

      const config = makeConfig(workspaceRoot, { dryRun: true });
      const status = await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const handWritten = false;\n`,
        config,
      );

      assert.equal(
        status,
        "skipped",
        "dry-run must report an existing hand-written file as 'skipped', not 'updated'",
      );
      assert.equal(
        await fs.readFile(target, "utf8"),
        "export const handWritten = true;\n",
        "dry-run MUST NOT modify a hand-written file",
      );
    });
  });

  describe("--only scope filter", () => {
    it("skips a file outside the scope without writing it", async () => {
      const target = path.join(workspaceRoot, "packages", "b", "src", "x.ts");
      const config = makeConfig(workspaceRoot, {
        only: ["packages/a"],
      });

      const status = await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const x = 1;\n`,
        config,
      );

      assert.equal(
        status,
        "skipped",
        "a file outside --only must be skipped, not written",
      );
      assert.equal(
        await pathExists(target),
        false,
        "out-of-scope file must not be created on disk",
      );
    });

    it("writes a file that is inside the scope", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "x.ts");
      const content = `${GENERATED_MARKER}\nexport const x = 1;\n`;
      const config = makeConfig(workspaceRoot, { only: ["packages/a"] });

      const status = await safeWriteFileAtomic(target, content, config);

      assert.equal(status, "created", "in-scope file must be written");
      assert.equal(await fs.readFile(target, "utf8"), content);
    });
  });

  describe("new-file creation", () => {
    it("writes a new file and returns 'created'", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "a.ts");
      const content = `${GENERATED_MARKER}\nexport const a = 1;\n`;
      const config = makeConfig(workspaceRoot);

      const status = await safeWriteFileAtomic(target, content, config);

      assert.equal(status, "created");
      assert.equal(await fs.readFile(target, "utf8"), content);
    });

    it("creates intermediate parent directories as needed", async () => {
      const target = path.join(
        workspaceRoot,
        "packages",
        "a",
        "src",
        "nested",
        "deep",
        "file.ts",
      );
      const content = `${GENERATED_MARKER}\nexport {};\n`;
      const config = makeConfig(workspaceRoot);

      const status = await safeWriteFileAtomic(target, content, config);

      assert.equal(status, "created");
      assert.equal(await fs.readFile(target, "utf8"), content);
      const parentStat = await fs.stat(path.dirname(target));
      assert.equal(parentStat.isDirectory(), true);
    });

    it("leaves no .tmp.* sibling behind on success", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "ok.ts");
      await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport {};\n`,
        makeConfig(workspaceRoot),
      );
      const siblings = await fs.readdir(path.dirname(target));
      const stray = siblings.filter((n) => n.includes(".tmp."));
      assert.deepEqual(stray, [], "temp file must be atomically renamed away");
    });
  });

  describe("updates & idempotency", () => {
    it("updates a generated file when content changes", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "m.ts");
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(
        target,
        `${GENERATED_MARKER}\nexport const v = 1;\n`,
        "utf8",
      );

      const next = `${GENERATED_MARKER}\nexport const v = 2;\n`;
      const status = await safeWriteFileAtomic(
        target,
        next,
        makeConfig(workspaceRoot),
      );

      assert.equal(status, "updated");
      assert.equal(await fs.readFile(target, "utf8"), next);
    });

    it("returns 'unchanged' when content hash is identical (idempotent)", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "i.ts");
      const content = `${GENERATED_MARKER}\nexport const v = 1;\n`;
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, content, "utf8");
      const statBefore = await fs.stat(target);

      await new Promise((r) => setTimeout(r, 5));

      const status = await safeWriteFileAtomic(
        target,
        content,
        makeConfig(workspaceRoot),
      );

      assert.equal(status, "unchanged");
      const statAfter = await fs.stat(target);
      assert.equal(
        statAfter.mtimeMs,
        statBefore.mtimeMs,
        "idempotent write MUST NOT touch the file",
      );
    });
  });

  describe("non-generated file protection", () => {
    it("returns 'skipped' and preserves content when file lacks the generated marker", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "h.ts");
      const handWritten =
        "// hand-written — DO NOT TOUCH\nexport const v = 1;\n";
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, handWritten, "utf8");

      const status = await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const v = 999;\n`,
        makeConfig(workspaceRoot),
      );

      assert.equal(status, "skipped");
      assert.equal(
        await fs.readFile(target, "utf8"),
        handWritten,
        "hand-written content must be preserved byte-for-byte",
      );
    });

    it("overwrites non-generated file when skipGeneratedCheck=true", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "package.json");
      const handWritten = '{ "name": "existing" }\n';
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, handWritten, "utf8");

      const next = '{ "name": "synced" }\n';
      const status = await safeWriteFileAtomic(
        target,
        next,
        makeConfig(workspaceRoot),
        undefined,
        /* skipGeneratedCheck */ true,
      );

      assert.equal(status, "updated");
      assert.equal(await fs.readFile(target, "utf8"), next);
    });

    it("force=true does NOT bypass hand-written protection (use --force-root instead)", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "f.ts");
      const handWritten = "export const v = 1;\n";
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, handWritten, "utf8");

      const logger = createSpyLogger();
      const next = `${GENERATED_MARKER}\nexport const v = 2;\n`;
      const status = await safeWriteFileAtomic(
        target,
        next,
        makeConfig(workspaceRoot, { force: true, logger }),
      );

      assert.equal(
        status,
        "skipped",
        "force=true MUST NOT overwrite hand-written files",
      );
      assert.equal(
        await fs.readFile(target, "utf8"),
        handWritten,
        "hand-written content must be preserved byte-for-byte even with --force",
      );
      assert.ok(
        logger.calls.some(
          (c) =>
            c.level === "warn" &&
            c.message.includes("hand-written") &&
            c.message.includes("--force-root"),
        ),
        "warn log must instruct the user to use --force-root",
      );
    });

    it("force-root=true DOES bypass hand-written protection (package file)", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "f.ts");
      const handWritten = "export const v = 1;\n";
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, handWritten, "utf8");

      const next = `${GENERATED_MARKER}\nexport const v = 2;\n`;
      const status = await safeWriteFileAtomic(
        target,
        next,
        makeConfig(workspaceRoot, { forceRoot: true }),
      );

      assert.equal(
        status,
        "updated",
        "forceRoot=true MUST overwrite even hand-written files (reserved escape hatch for deliberate mass-migrations)",
      );
      assert.equal(await fs.readFile(target, "utf8"), next);
    });
  });

  describe("protected root files", () => {
    it("refuses to overwrite .gitignore at workspace root without --force-root", async () => {
      const target = path.join(workspaceRoot, ".gitignore");
      const original = "node_modules\n";
      await fs.writeFile(target, original, "utf8");

      const logger = createSpyLogger();
      const report = createSpyReport();
      const config = makeConfig(workspaceRoot, { logger });

      const status = await safeWriteFileAtomic(
        target,
        "dist\n",
        config,
        report,
      );

      assert.equal(status, "protected");
      assert.equal(
        await fs.readFile(target, "utf8"),
        original,
        "protected root file MUST NOT be modified",
      );
      assert.equal(
        report.entries.length,
        1,
        "report must record one blocked entry",
      );
      assert.deepEqual(report.entries[0], {
        type: "blocked",
        target,
        message: "Root file protected",
      });
      assert.ok(
        logger.calls.some(
          (c) => c.level === "warn" && c.message.includes("root protected"),
        ),
        "warn log must mention root protection",
      );
    });

    it("protects turbo.json and yarn.lock at workspace root", async () => {
      for (const name of ["turbo.json", "yarn.lock"]) {
        const target = path.join(workspaceRoot, name);
        const original = `ORIGINAL ${name}\n`;
        await fs.writeFile(target, original, "utf8");

        const status = await safeWriteFileAtomic(
          target,
          "OVERWRITE\n",
          makeConfig(workspaceRoot),
        );

        assert.equal(status, "protected", `${name} must be protected`);
        assert.equal(await fs.readFile(target, "utf8"), original);
      }
    });

    it("does NOT call report.record for protected root when report is omitted", async () => {
      const target = path.join(workspaceRoot, ".gitignore");
      await fs.writeFile(target, "node_modules\n", "utf8");

      const status = await safeWriteFileAtomic(
        target,
        "dist\n",
        makeConfig(workspaceRoot),
      );
      assert.equal(status, "protected");
    });

    it("allows overwrite when forceRoot=true", async () => {
      const target = path.join(workspaceRoot, ".gitignore");
      await fs.writeFile(target, "old\n", "utf8");

      const status = await safeWriteFileAtomic(
        target,
        "new\n",
        makeConfig(workspaceRoot, { forceRoot: true }),
      );

      assert.equal(status, "updated");
      assert.equal(await fs.readFile(target, "utf8"), "new\n");
    });

    it("does NOT consider .gitignore inside packages/ a root-protected file", async () => {
      const target = path.join(workspaceRoot, "packages", "a", ".gitignore");
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, "dist\n", "utf8");

      const status = await safeWriteFileAtomic(
        target,
        "dist\nnode_modules\n",
        makeConfig(workspaceRoot),
      );

      assert.equal(
        status,
        "skipped",
        "non-root .gitignore falls through to non-generated protection, not root protection",
      );
    });
  });

  describe("atomic semantics & error handling", () => {
    it("propagates errors from rename and cleans up the temp file", async () => {
      const target = path.join(
        workspaceRoot,
        "packages",
        "a",
        "src",
        "atomic.ts",
      );
      const original = `${GENERATED_MARKER}\nexport const v = 1;\n`;
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, original, "utf8");

      const originalRename = fs.rename;
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      (fs as any).rename = async () => {
        const err = new Error("simulated EACCES") as NodeJS.ErrnoException;
        err.code = "EACCES";
        throw err;
      };

      try {
        await assert.rejects(
          () =>
            safeWriteFileAtomic(
              target,
              `${GENERATED_MARKER}\nexport const v = 2;\n`,
              makeConfig(workspaceRoot),
            ),
          /simulated EACCES/,
          "rename failure must surface as a thrown error — never silently swallowed",
        );

        assert.equal(
          await fs.readFile(target, "utf8"),
          original,
          "on failed rename, original file content MUST remain unchanged",
        );

        const siblings = await fs.readdir(path.dirname(target));
        const stray = siblings.filter((n) => n.includes(".tmp."));
        assert.deepEqual(
          stray,
          [],
          "temp file MUST be unlinked after a failed rename",
        );
      } finally {
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        (fs as any).rename = originalRename;
      }
    });

    it("re-throws read errors other than ENOENT (never swallows silently)", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "r.ts");
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, "x", "utf8");
      await fs.chmod(target, 0o000);

      try {
        await fs.readFile(target, "utf8");
        return;
      } catch {
        // Good: readFile throws as expected.
      }

      try {
        await assert.rejects(
          () => safeWriteFileAtomic(target, "new", makeConfig(workspaceRoot)),
          "non-ENOENT read errors must propagate, never be silently swallowed",
        );
      } finally {
        await fs.chmod(target, 0o644).catch(() => {});
      }
    });
  });

  describe("report recording", () => {
    it("does NOT record ordinary creates / updates / unchanged writes", async () => {
      const target = path.join(workspaceRoot, "packages", "a", "src", "p.ts");
      const report = createSpyReport();
      const config = makeConfig(workspaceRoot);

      await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const v = 1;\n`,
        config,
        report,
      );
      await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const v = 1;\n`,
        config,
        report,
      );
      await safeWriteFileAtomic(
        target,
        `${GENERATED_MARKER}\nexport const v = 2;\n`,
        config,
        report,
      );

      assert.deepEqual(
        report.entries,
        [],
        "report.record is only invoked for protected-root blocks",
      );
    });

    it("records 'blocked' in the report when a protected root file is refused", async () => {
      const target = path.join(workspaceRoot, "turbo.json");
      await fs.writeFile(target, "{}\n", "utf8");
      const report = createSpyReport();

      const status = await safeWriteFileAtomic(
        target,
        '{ "new": true }\n',
        makeConfig(workspaceRoot),
        report,
      );

      assert.equal(status, "protected");
      assert.equal(report.entries.length, 1);
      assert.equal(report.entries[0].type, "blocked");
      assert.equal(report.entries[0].target, target);
      assert.equal(report.entries[0].message, "Root file protected");
    });
  });
});

describe("safeWriteFile (wrapper)", () => {
  let workspaceRoot: string;

  beforeEach(async () => {
    workspaceRoot = await makeTmpWorkspace();
  });

  afterEach(async () => {
    await fs.rm(workspaceRoot, { recursive: true, force: true });
  });

  it("delegates to safeWriteFileAtomic without a report", async () => {
    const target = path.join(workspaceRoot, "packages", "a", "src", "w.ts");
    const content = `${GENERATED_MARKER}\nexport {};\n`;

    const status = await safeWriteFile(
      target,
      content,
      makeConfig(workspaceRoot),
    );

    assert.equal(status, "created");
    assert.equal(await fs.readFile(target, "utf8"), content);
  });

  it("forwards skipGeneratedCheck=true to bypass non-generated protection", async () => {
    const target = path.join(workspaceRoot, "packages", "a", "package.json");
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, '{ "old": true }\n', "utf8");

    const next = '{ "new": true }\n';
    const status = await safeWriteFile(
      target,
      next,
      makeConfig(workspaceRoot),
      /* skipGeneratedCheck */ true,
    );

    assert.equal(status, "updated");
    assert.equal(await fs.readFile(target, "utf8"), next);
  });
});
