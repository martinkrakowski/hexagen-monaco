const GENERATED_MARKER = "// @generated by @hexagen/sync";

interface RecordedOp {
  type: string;
  target: string;
  message: string;
}

function createSpyReport(): {
  record: (t: string, target: string, msg: string) => void;
  entries: RecordedOp[];
} {
  const entries: RecordedOp[] = [];
  return {
    entries,
    record: (type, target, message) => {
      entries.push({ type, target, message });
    },
  };
}

describe("isGeneratedFile", () => {
  it("returns true when content contains the generated marker", () => {
    assert.equal(isGeneratedFile(`${GENERATED_MARKER}\nexport {};\n`), true);
  });

  it("returns false when the marker is absent", () => {
    assert.equal(isGeneratedFile("// hand-written code\nexport {};\n"), false);
  });

  it("returns false for empty content", () => {
    assert.equal(isGeneratedFile(""), false);
  });
});

describe("isProtectedRoot", () => {
  let workspaceRoot: string;
  let config: SyncConfig;

  beforeEach(async () => {
    workspaceRoot = await makeTmpWorkspace();
    config = makeConfig(workspaceRoot);
  });

  afterEach(async () => {
    await fs.rm(workspaceRoot, { recursive: true, force: true });
  });

  it("identifies root-level protected files", () => {
    for (const name of [".gitignore", "turbo.json", "yarn.lock"]) {
      assert.equal(
        isProtectedRoot(path.join(workspaceRoot, name), config),
        true,
        `${name} at workspace root must be protected`,
      );
    }
  });

  it("does NOT protect files inside packages/", () => {
    assert.equal(
      isProtectedRoot(
        path.join(workspaceRoot, "packages", "foo", "turbo.json"),
        config,
      ),
      false,
      "nested turbo.json inside packages/ must NOT be treated as root-protected",
    );
  });

  it("does NOT protect files inside apps/ or tools/", () => {
    assert.equal(
      isProtectedRoot(
        path.join(workspaceRoot, "apps", "web", ".gitignore"),
        config,
      ),
      false,
    );
    assert.equal(
      isProtectedRoot(
        path.join(workspaceRoot, "tools", "x", "yarn.lock"),
        config,
      ),
      false,
    );
  });

  it("exposes the canonical protected-files set", () => {
    assert.ok(protectedFiles.has(".gitignore"));
    assert.ok(protectedFiles.has("turbo.json"));
    assert.ok(protectedFiles.has("yarn.lock"));
  });
});

